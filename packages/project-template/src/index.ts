export const manifestPageSchema = z.object({
  id: z.uuid(),
  name: z.string().min(1).max(80),
  route: z.string().max(120),
  /** Folder under src/pages (slug, fixed at creation). */
  folder: z.string().regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/),
  component: z.string().regex(/^[A-Z][A-Za-z0-9]*$/),
});
export type ManifestPage = z.infer<typeof manifestPageSchema>;

export const manifestSchema = z.object({
  schemaVersion: z.literal(1),
  templateVersion: z.string(),
  pages: z.array(manifestPageSchema).min(1),
});
export type Manifest = z.infer<typeof manifestSchema>;

export const pageFilePath = (page: Pick<ManifestPage, 'folder' | 'component'>) =>
  `src/pages/${page.folder}/${page.component}.tsx`;

/** "Getting Started" → "getting-started"; empty → "page". */
export function slugify(name: string): string {
  const slug = name
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 40)
    .replace(/-+$/g, '');
  return slug || 'page';
}

/** "getting-started" → "GettingStartedPage"; names starting with a digit get a "Page" prefix. */
export function componentNameFor(folder: string): string {
  const pascal = folder
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
  return /^[0-9]/.test(pascal) ? `Page${pascal}` : `${pascal}Page`;
}

/** Picks a folder not used by other pages: "pricing", "pricing-2", … */
export function uniqueFolder(name: string, existing: readonly string[]): string {
  const base = slugify(name);
  if (!existing.includes(base)) return base;
  for (let i = 2; ; i++) {
    const candidate = `${base}-${String(i)}`;
    if (!existing.includes(candidate)) return candidate;
  }
}

export function renderManifest(manifest: Manifest): string {
  return `${JSON.stringify(manifestSchema.parse(manifest), null, 2)}\n`;
}

export function parseManifest(text: string): Manifest {
  return manifestSchema.parse(JSON.parse(text));
}

/** The generated route table: one lazy import per page, in manifest order. */
export function renderRoutes(manifest: Manifest): string {
  const lines = manifest.pages.map(
    (page) =>
      `  { path: ${JSON.stringify(page.route)}, Component: lazy(() => import(${JSON.stringify(
        `../pages/${page.folder}/${page.component}`,
      )})) },`,
  );
  return [
    '// Generated by CORE Studio from core.project.json. Do not edit: changes are overwritten.',
    "import { lazy } from 'react';",
    '',
    'export const routes = [',
    ...lines,
    '];',
    '',
  ].join('\n');
}

/** A new page: plain, idiomatic React + Tailwind. The title is emitted as a JS string literal. */
export function renderPageStub(page: Pick<ManifestPage, 'component' | 'name'>): string {
  return [
    `export default function ${page.component}() {`,
    '  return (',
    '    <section className="mx-auto max-w-5xl px-6 py-16">',
    `      <h1 className="text-3xl font-semibold tracking-tight">{${JSON.stringify(page.name)}}</h1>`,
    '      <p className="mt-4 text-base text-slate-600">This page is ready to design.</p>',
    '    </section>',
    '  );',
    '}',
    '',
  ].join('\n');
}

export const templateDir = (): string => fileURLToPath(new URL('../template', import.meta.url));

/** Template files as repo-relative POSIX paths → contents. `gitignore` becomes `.gitignore`. */
export async function readTemplateFiles(): Promise<Map<string, Buffer>> {
  const root = templateDir();
  const files = new Map<string, Buffer>();
  const walk = async (dir: string): Promise<void> => {
    for (const entry of await readdir(dir, { withFileTypes: true })) {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) await walk(full);
      else if (entry.isFile()) {
        const rel = relative(root, full).split(sep).join('/');
        files.set(rel === 'gitignore' ? '.gitignore' : rel, await readFile(full));
      }
    }
  };
  await walk(root);
  return files;
}

/** Everything a new project contains: template files + generated manifest, routes and pages. */
export async function renderProject(
  pages: readonly Pick<ManifestPage, 'id' | 'name' | 'route'>[],
): Promise<{ files: Map<string, Buffer>; manifest: Manifest }> {
  const folders: string[] = [];
  const manifestPages = pages.map((page) => {
    const folder = uniqueFolder(page.name, folders);
    folders.push(folder);
    return { ...page, folder, component: componentNameFor(folder) };
  });
  const manifest: Manifest = {
    schemaVersion: 1,
    templateVersion: TEMPLATE_VERSION,
    pages: manifestPages,
  };
  const files = await readTemplateFiles();
  files.set(MANIFEST_PATH, Buffer.from(renderManifest(manifest)));
  files.set(ROUTES_PATH, Buffer.from(renderRoutes(manifest)));
  for (const page of manifestPages)
    files.set(pageFilePath(page), Buffer.from(renderPageStub(page)));
  return { files, manifest };
}
