import { readdir, readFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { z } from 'zod';

/**
 * CORE Studio project template (PROJECT_REPOSITORY_DESIGN.md §4). Template files live in
 * `../template`; this module renders the generated parts (manifest, routes, page stubs).
 */
export const TEMPLATE_VERSION = '1';
export const MANIFEST_PATH = 'core.project.json';
export const ROUTES_PATH = 'src/app/routes.ts';

/** Files the edit pipeline must never change; only generators and template upgrades write them. */
export const MANAGED_FILES: readonly string[] = [
  MANIFEST_PATH,
  ROUTES_PATH,
  'src/main.tsx',
  'src/app/App.tsx',
  'vite.config.ts',
  'tsconfig.json',
  'package.json',
  'index.html',
];

/** Allow-listed runtime and build dependencies (D11). Exact versions only. */
